const operatorSprites = new Map<string, OperatorSprite>(
  operatorSheetSlugs.map((sheetSlug, index) => [
    operatorSheetSlugAliases[sheetSlug] ?? sheetSlug,
    { column: index % 7, row: Math.floor(index / 7) },
  ]),
);

export function getOperatorSprite(slug: string): OperatorSprite | undefined {
  return operatorSprites.get(slug);
}

